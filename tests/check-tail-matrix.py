#!/usr/bin/env python3
"""Validate unequal-track native probe results on wall time, presentation, audio, and end.
Native probe JSON is generated by tests/movie-tail-probe.cc. 'normal' assumes the
4s short-audio/short-video, 1.5s delayed-audio, and 4s silent reference fixtures.
"""
import json,sys
from pathlib import Path
if len(sys.argv)<2:raise SystemExit('usage: check-tail-matrix.py result.json')
rows=json.loads(Path(sys.argv[1]).read_text());passed=[]
for r in rows:
    mode=r['mode'];name=r['file'];assert not r['error'],r
    if mode=='loop':
        t=r['soundOnsets'];assert len(t)==3 and all(abs(v-i*4)<.16 for i,v in enumerate(t)),r
        assert r['tailOnsets']>=2 and not r['ended'] and r['backsteps']==2,r
    elif mode=='pause-last':
        assert r['ended'] and not r['endedWhilePaused'] and r['pauseTargetError']<.002 and r['wall']>=4.35 and r['lastFrameTailColor'],r
    elif mode in ('seek','seek-pause'):
        assert r['ended'] and r['lastFrameTailColor'] and r['mediaTime']>3.97 and r['backsteps']==0 and r['pauseTargetError']<.002,r
        assert (2.7<=r['wall']<=3.1) if mode=='seek-pause' else (2.3<=r['wall']<=2.65),r
    else:
        assert r['ended'] and r['lastFrameTailColor'] and r['backsteps']==0 and r['maxMediaTime']>=3.96,r
        if mode=='pause':assert r['pauseDrift']<.002 and not r['endedWhilePaused'] and 4.32<r['wall']<4.58,r
        else:assert 3.9<r['wall']<4.15,r
        if name.startswith('short-video'):
            assert r['presented']+r['dropped']==24 and .57<r['firstTailColorWall']<.9 and r['audibleThroughWall']>3.83,r
        else:
            assert r['presented']+r['dropped']==96 and r['firstTailColorWall']>=3.38,r
        if name.startswith('short-audio'):assert .85<r['audibleThroughWall']<1.16,r
        if name.startswith('delayed'):assert len(r['soundOnsets'])==1 and 1.39<=r['soundOnsets'][0]<=1.59 and 2.08<r['audibleThroughWall']<2.32,r
        if name.startswith('silent'):assert r['peakL']==r['peakR']==0,r
    passed.append(name+':'+mode)
print(f'{len(passed)} unequal-track cases passed: '+', '.join(passed));
